#!/usr/bin/env node
// Writes app/styles/sj-tokens.css, Spoonjoy's colours, radii, shadows and type families, from the
// Cookbook theme that ouro-ui-core publishes (vendor/ouro-ui-core/cookbook.css, pinned by sha256
// in vendor/ouro-ui-core/pin.json). The native app reads the same theme through OuroTokens.swift,
// so web and native share one source.
//
// Only the --sj-* and --font-sj-* declarations of the theme's `:root` and `.dark` blocks are
// copied. The rest of core's file (its Geist @font-face rules, --font-sans, the --shadow-*,
// --chart-* and --sidebar-* scales, and its prefers-color-scheme block) is for pages without an
// app of their own, and would change what Spoonjoy shows.
//
//   node scripts/sync-sj-tokens.mjs             write the file
//   node scripts/sync-sj-tokens.mjs --check     exit 1 if the file is not what this would write
//   node scripts/sync-sj-tokens.mjs --snapshot  rewrite test/styles/sj-tokens.snapshot.json from it
//
// To take a new core release: replace vendor/ouro-ui-core/cookbook.css with that release's
// web/themes/cookbook.css, update pin.json's tag and sha256, and run this. Then run
// test/styles/sj-token-parity.test.ts: it holds every token to test/styles/sj-tokens.snapshot.json,
// so a release that changes what Spoonjoy paints fails there until you mean the change and run
// `node scripts/sync-sj-tokens.mjs --snapshot`, which rewrites the snapshot from the new file.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const VENDOR = resolve(ROOT, "vendor/ouro-ui-core/cookbook.css");
const PIN = resolve(ROOT, "vendor/ouro-ui-core/pin.json");
const OUT = resolve(ROOT, "app/styles/sj-tokens.css");
const SNAPSHOT = resolve(ROOT, "test/styles/sj-tokens.snapshot.json");

const TOKEN = /(--(?:sj|font-sj)-[\w-]+)\s*:\s*([^;]+);/g;

// The token declarations of every top-level rule whose selector is exactly `selector`, in order.
export function declarations(css, selector) {
  const source = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const rule = new RegExp(`(?<=^|\\})\\s*${selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\s*\\{([^}]*)\\}`, "g");
  const bodies = Array.from(source.matchAll(rule), (match) => match[1]);
  const tokens = Object.fromEntries(bodies.flatMap((body) => Array.from(body.matchAll(TOKEN), (m) => [m[1], m[2].trim()])));
  if (Object.keys(tokens).length === 0) throw new Error(`no Spoonjoy tokens in a "${selector} {" rule of ${VENDOR}`);
  return tokens;
}

export function render(css, pin) {
  const light = declarations(css, ":root");
  const dark = declarations(css, ".dark");
  const lines = (tokens) => Object.entries(tokens).map(([name, value]) => `  ${name}: ${value};`).join("\n");
  return `/*
 * Spoonjoy's tokens, generated by scripts/sync-sj-tokens.mjs from ouro-ui-core ${pin.tag}'s Cookbook
 * theme (vendor/ouro-ui-core/cookbook.css). Don't edit; change the theme in Ouro and sync.
 * Contrast is tested by test/styles/primary-button-contrast.test.ts and ouro-theme-mapping.test.ts.
 */

:root {
  color-scheme: light;
${lines(light)}
}

.dark {
  color-scheme: dark;
${lines(dark)}
}
`;
}

export function build() {
  const css = readFileSync(VENDOR, "utf8");
  const pin = JSON.parse(readFileSync(PIN, "utf8"));
  const sha256 = createHash("sha256").update(css).digest("hex");
  if (sha256 !== pin.sha256) {
    throw new Error(`vendor/ouro-ui-core/cookbook.css is sha256 ${sha256}, but pin.json says ${pin.sha256}`);
  }
  return render(css, pin);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = build();
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== output) {
      console.error("app/styles/sj-tokens.css is out of date: run node scripts/sync-sj-tokens.mjs");
      process.exit(1);
    }
  } else if (process.argv.includes("--snapshot")) {
    const { tag } = JSON.parse(readFileSync(PIN, "utf8"));
    const source = `app/styles/sj-tokens.css from ouro-ui-core ${tag}`;
    const snapshot = { source, light: declarations(output, ":root"), dark: declarations(output, ".dark") };
    writeFileSync(SNAPSHOT, `${JSON.stringify(snapshot, null, 2)}\n`);
  } else {
    writeFileSync(OUT, output);
  }
}
